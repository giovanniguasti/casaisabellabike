function normalizeLang(lang) {
  return lang === "en" ? "en" : "it";
}

function getInitialLang() {
  const urlLang = new URLSearchParams(window.location.search).get("lang");
  if (urlLang) return normalizeLang(urlLang);
  try {
    const stored = localStorage.getItem("cib_lang");
    if (stored) return normalizeLang(stored);
  } catch (_) { /* The URL also preserves language when storage is unavailable. */ }
  return normalizeLang((navigator.language || "").slice(0, 2));
}

function setLang(lang) {
  const normalized = normalizeLang(lang);
  const dict = I18N[normalized];
  document.documentElement.lang = normalized;
  try { localStorage.setItem("cib_lang", normalized); } catch (_) { /* Optional storage. */ }

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const value = dict[el.dataset.i18n];
    if (typeof value === "string") el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(el => {
    const value = dict[el.dataset.i18nAlt];
    if (typeof value === "string") el.alt = value;
  });
  document.querySelector("nav").setAttribute("aria-label", dict["nav.label"]);
  document.querySelectorAll(".lang-switch button").forEach(button => {
    button.setAttribute("aria-pressed", String(button.id === `lang-${normalized}`));
  });

  const page = document.body.dataset.page;
  document.title = dict[`meta.${page}.title`];
  document.querySelector('meta[name="description"]').content = dict[`meta.${page}.description`];

  // Explicit links keep the selected language across direct visits and new tabs.
  document.querySelectorAll('a[href]').forEach(link => {
    const url = new URL(link.getAttribute("href"), window.location.href);
    if (url.origin === window.location.origin && url.pathname.endsWith(".html")) {
      url.searchParams.set("lang", normalized);
      link.setAttribute("href", url.pathname.split("/").pop() + url.search + url.hash);
    }
  });
  const url = new URL(window.location.href);
  url.searchParams.set("lang", normalized);
  try { history.replaceState(null, "", url); } catch (_) { /* Direct file preview. */ }
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: normalized } }));
}

document.getElementById("lang-it").addEventListener("click", () => setLang("it"));
document.getElementById("lang-en").addEventListener("click", () => setLang("en"));
setLang(getInitialLang());
